#!/usr/bin/env python3
"""Complaint-share trend over comparable periods (no model calls).

The review window starts on 2022-05-17 and ends on 2023-11-15, so the first and
last calendar months are partial. This script compares only full months:

* every full month with its denominator (classified rows) and numerator
  (complaint + cancellation rows);
* the same five full months one year apart (June–October 2022 vs June–October 2023).

Inputs: ``grading/records.jsonl.gz`` and the raw CSV (for ``review_timestamp``).
Outputs: ``artifacts/full_run_v4/trend_comparison.json`` and ``.md``.

Usage: python3 scripts/trend_comparison.py [--raw-csv data/spotify_reviews_18months.csv]
"""

from __future__ import annotations

import argparse
import csv
import gzip
import json
from collections import Counter
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def share(num: int, den: int) -> str:
    return str((Decimal(num) / Decimal(den)).quantize(Decimal("0.000001"), rounding=ROUND_HALF_UP)) if den else ""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw-csv", type=Path, default=ROOT / "data/spotify_reviews_18months.csv")
    parser.add_argument("--records", type=Path, default=ROOT / "grading/records.jsonl.gz")
    parser.add_argument("--out-dir", type=Path, default=ROOT / "artifacts/full_run_v4")
    args = parser.parse_args()
    month_of: dict[str, str] = {}
    stamps = []
    with args.raw_csv.open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            month_of[row["review_id"]] = row["review_timestamp"][:7]
            stamps.append(row["review_timestamp"])
    first_day, last_day = min(stamps)[:10], max(stamps)[:10]
    partial = {first_day[:7], last_day[:7]}
    classified, complaints, quarantined = Counter(), Counter(), Counter()
    with gzip.open(args.records, "rt", encoding="utf-8") as stream:
        for line in stream:
            record = json.loads(line)
            month = month_of[record["review_id"]]
            if record["status"] != "completed":
                quarantined[month] += 1
                continue
            classified[month] += 1
            if record["intent"] in ("complaint", "cancellation"):
                complaints[month] += 1
    months = [
        {"month": month, "partial_month": month in partial, "classified_rows": classified[month],
         "complaint_or_cancellation_rows": complaints[month], "quarantined_rows": quarantined[month],
         "share": share(complaints[month], classified[month])}
        for month in sorted(classified)
    ]

    def window(year: int) -> dict:
        keys = [f"{year}-{m:02d}" for m in range(6, 11)]
        num, den = sum(complaints[k] for k in keys), sum(classified[k] for k in keys)
        return {"months": keys, "complaint_or_cancellation_rows": num, "classified_rows": den, "share": share(num, den)}

    report = {
        "window": {"first_day": first_day, "last_day": last_day, "partial_months": sorted(partial)},
        "definition": "share = completed complaint+cancellation rows / completed (classified) rows in the month; quarantined empty texts excluded",
        "months": months,
        "year_over_year_full_months": {"2022": window(2022), "2023": window(2023)},
        "notes": [
            "Review volume is not constant: July 2023, September 2023 and October 2023 have far more reviews than other months, so a shift in who writes reviews can move the share as much as a product change.",
            "Shares are of self-selected reviews, not of the user base; they describe review content, not churn.",
        ],
        "model_calls": 0,
    }
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "trend_comparison.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    yoy = report["year_over_year_full_months"]
    lines = [
        "# Complaint share over time (comparable periods)",
        "",
        f"Generated by `scripts/trend_comparison.py` (no model calls). Window {first_day} to {last_day}; "
        f"{' and '.join(sorted(partial))} are partial months and are marked. Share = complaint + cancellation rows / classified rows.",
        "",
        "| Period | Complaint + cancellation | Classified | Share |",
        "|---|---:|---:|---:|",
        f"| Jun–Oct 2022 (full months) | {yoy['2022']['complaint_or_cancellation_rows']:,} | {yoy['2022']['classified_rows']:,} | {yoy['2022']['share']} |",
        f"| Jun–Oct 2023 (full months) | {yoy['2023']['complaint_or_cancellation_rows']:,} | {yoy['2023']['classified_rows']:,} | {yoy['2023']['share']} |",
        "",
        "| Month | Complaint + cancellation | Classified | Share |",
        "|---|---:|---:|---:|",
    ]
    for item in months:
        label = item["month"] + (" (partial)" if item["partial_month"] else "")
        lines.append(f"| {label} | {item['complaint_or_cancellation_rows']:,} | {item['classified_rows']:,} | {item['share']} |")
    lines += ["", *[f"- {note}" for note in report["notes"]], ""]
    (args.out_dir / "trend_comparison.md").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps(yoy, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
